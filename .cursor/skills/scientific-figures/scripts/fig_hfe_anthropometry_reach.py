"""Seated reach envelopes for three body sizes, and what they accommodate.

Main panel: a side view of a seated operator drawn as a linkage on an
equal-aspect millimetre grid, with the grip reach envelope of the 5th
percentile female, the 50th percentile and the 95th percentile male drawn as
nested annular sectors generated by the forward kinematics of the shoulder,
elbow and grip links.  Five hand controls are tested against the envelopes:
the marker colour is decided by the same geometry that drew the arcs, never
by hand.  The downward sight cone from the eye point is shown for reference.

Auxiliary (both at 58 % of the main panel width): the functional reach
distributions for women, men and the pooled population, with the 5th, 50th
and 95th percentiles marked; and the share of the pooled population that can
reach each control, read off the same cumulative distribution.

Fictional survey, illustrative values only.
"""
import textwrap

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import Circle, Polygon, Rectangle

from pubstyle import set_pub_style, savefig, style_axes, lighten
from figkit import axes_inches, panel_labels_inches

INK = "#1a1a1a"
SUB = "#555555"
MUTED = "#777777"
FAINT = "#8a8a8a"
GRID = "#d5d5d5"
TEAL = "#2e7d5b"
AMBER = "#c9a227"
RUST = "#c0603f"
BLUE = "#3b5b92"
ACCENT = "#b23a48"

FIG_W, FIG_H = 11.0, 6.5
MAIN_RECT = (0.86, 0.86, 5.54, 4.62)
AUX_T_RECT = (7.62, 3.48, 3.16, 2.00)
AUX_B_RECT = (7.62, 0.86, 3.16, 2.00)

# functional grip reach, mm: two sex-specific normals, pooled 50/50
MU_F, SD_F = 700.0, 40.0
MU_M, SD_M = 772.0, 42.0
UPPER_FRAC = 0.45           # share of the reach taken by the upper arm link
ELBOW_MAX_DEG = 140.0       # maximum elbow flexion
TH_LO, TH_HI = -55.0, 75.0  # shoulder sweep limits about the horizontal, deg

HIP = np.array([0.0, 0.0])
TORSO = 560.0
TORSO_LEAN = 12.0           # backward lean of the torso link, deg

CONTROLS = [
    ("emergency stop", 430.0, -5.0),
    ("mode selector", 560.0, 25.0),
    ("throttle lever", 620.0, -20.0),
    ("trim wheel", 700.0, -45.0),
    ("aux breaker panel", 790.0, -10.0),
]


def reach_distributions(n=1400):
    """Grid, sex-specific densities, pooled density and pooled CDF."""
    g = np.linspace(520.0, 980.0, n)
    pdf_f = np.exp(-0.5 * ((g - MU_F) / SD_F) ** 2) / (SD_F * np.sqrt(2 * np.pi))
    pdf_m = np.exp(-0.5 * ((g - MU_M) / SD_M) ** 2) / (SD_M * np.sqrt(2 * np.pi))
    pdf_p = 0.5 * (pdf_f + pdf_m)
    cdf = np.concatenate([[0.0], np.cumsum(np.diff(g) * 0.5
                                           * (pdf_p[1:] + pdf_p[:-1]))])
    cdf = cdf / cdf[-1]
    return g, pdf_f, pdf_m, pdf_p, cdf


def percentile_reach(g, cdf, q):
    return float(np.interp(q, cdf, g))


def accommodated(g, cdf, r):
    """Share of the pooled population whose reach exceeds ``r`` (%)."""
    return 100.0 * (1.0 - float(np.interp(r, g, cdf)))


def envelope(shoulder, reach):
    """Outer and inner boundary of the sector swept by the arm linkage."""
    l_up = UPPER_FRAC * reach
    l_fore = reach - l_up
    inner = np.sqrt(l_up ** 2 + l_fore ** 2 - 2.0 * l_up * l_fore
                    * np.cos(np.deg2rad(180.0 - ELBOW_MAX_DEG)))
    th = np.deg2rad(np.linspace(TH_LO, TH_HI, 160))
    out = shoulder[None, :] + reach * np.column_stack([np.cos(th), np.sin(th)])
    inn = shoulder[None, :] + inner * np.column_stack([np.cos(th), np.sin(th)])
    return out, inn[::-1], inner


def link(ax, p0, p1, color, lw=3.4, zorder=8):
    ax.plot([p0[0], p1[0]], [p0[1], p1[1]], color=color, lw=lw,
            solid_capstyle="round", zorder=zorder)


def joint(ax, p, color, r=17.0, zorder=9):
    ax.add_patch(Circle(tuple(p), r, facecolor="white", edgecolor=color,
                        lw=1.4, zorder=zorder))


def main():
    set_pub_style(base_font=8)

    g, pdf_f, pdf_m, pdf_p, cdf = reach_distributions()
    r05 = percentile_reach(g, cdf, 0.05)
    r50 = percentile_reach(g, cdf, 0.50)
    r95 = percentile_reach(g, cdf, 0.95)

    shoulder = HIP + TORSO * np.array([-np.sin(np.deg2rad(TORSO_LEAN)),
                                       np.cos(np.deg2rad(TORSO_LEAN))])
    head_c = shoulder + np.array([-24.0, 170.0])
    eye = head_c + np.array([78.0, 26.0])

    fig = plt.figure(figsize=(FIG_W, FIG_H))
    ax = axes_inches(fig, MAIN_RECT)
    ax_t = axes_inches(fig, AUX_T_RECT)
    ax_b = axes_inches(fig, AUX_B_RECT)
    for a in (ax, ax_t, ax_b):
        a.set_axisbelow(True)
        style_axes(a)

    # ---- main: linkage, envelopes and control points -----------------------
    ax.set_aspect("equal")
    ax.grid(color=GRID, lw=0.5, alpha=0.55, zorder=0)

    tiers = [(r95, "#9cc3dd", "95th percentile male"),
             (r50, "#5f9dc6", "50th percentile"),
             (r05, "#134a76", "5th percentile female")]
    for reach, col, lab in tiers:
        out, inn, _ = envelope(shoulder, reach)
        poly = np.vstack([out, inn])
        ax.add_patch(Polygon(poly, closed=True, facecolor=lighten(col, 0.62),
                             edgecolor="none", alpha=0.75, zorder=2))
        ax.plot(out[:, 0], out[:, 1], color=col, lw=1.3, zorder=3)
    _, inn05, inner_r = envelope(shoulder, r05)
    ax.plot(inn05[:, 0], inn05[:, 1], color="#134a76", lw=0.9,
            ls=(0, (3.0, 2.2)), zorder=3)

    # seat and floor reference
    ax.add_patch(Rectangle((-330.0, -70.0), 640.0, 70.0, facecolor="#ececec",
                           edgecolor="#c4c4c4", lw=0.8, zorder=1))
    ax.plot([-330.0, -330.0], [-70.0, 480.0], color="#c4c4c4", lw=6.0,
            solid_capstyle="round", zorder=1)
    ax.plot([-420.0, 1130.0], [-430.0, -430.0], color="#b8b8b8", lw=1.2,
            zorder=1)
    ax.text(1120.0, -420.0, "floor", ha="right", va="bottom", fontsize=6.4,
            color=MUTED)

    # sight cone from the eye point
    for half in (-15.0, 15.0):
        a_deg = -14.0 + half
        end = eye + 980.0 * np.array([np.cos(np.deg2rad(a_deg)),
                                      np.sin(np.deg2rad(a_deg))])
        ax.plot([eye[0], end[0]], [eye[1], end[1]], color=BLUE, lw=0.8,
                ls=(0, (4.0, 2.4)), alpha=0.75, zorder=4)
    cone = np.deg2rad(np.linspace(-29.0, 1.0, 40))
    arc = eye[None, :] + 980.0 * np.column_stack([np.cos(cone), np.sin(cone)])
    ax.add_patch(Polygon(np.vstack([eye[None, :], arc]), closed=True,
                         facecolor=lighten(BLUE, 0.88), edgecolor="none",
                         alpha=0.55, zorder=1))
    ax.text(700.0, 900.0, "sight cone, 30 deg about the\n-14 deg line of "
            "sight", ha="left", va="top", fontsize=6.3, color=BLUE,
            linespacing=1.4)

    # the seated linkage, 50th percentile
    knee = HIP + np.array([452.0, 22.0])
    ankle = knee + np.array([46.0, -392.0])
    toe = ankle + np.array([158.0, -34.0])
    # the drawn arm is placed by inverse kinematics onto the throttle lever,
    # so the posture and the envelope come from the same link lengths
    l_up, l_fore = UPPER_FRAC * r50, (1.0 - UPPER_FRAC) * r50
    r_t, th_t = CONTROLS[2][1], np.deg2rad(CONTROLS[2][2])
    grip = shoulder + r_t * np.array([np.cos(th_t), np.sin(th_t)])
    cos_a = np.clip((r_t ** 2 + l_up ** 2 - l_fore ** 2)
                    / (2.0 * r_t * l_up), -1.0, 1.0)
    a_el = th_t - np.arccos(cos_a)
    elbow = shoulder + l_up * np.array([np.cos(a_el), np.sin(a_el)])
    link(ax, HIP, shoulder, INK)
    link(ax, HIP, knee, INK)
    link(ax, knee, ankle, INK)
    link(ax, ankle, toe, INK, lw=2.6)
    link(ax, shoulder, elbow, ACCENT, lw=3.0)
    link(ax, elbow, grip, ACCENT, lw=3.0)
    ax.add_patch(Circle(tuple(head_c), 96.0, facecolor="white",
                        edgecolor=INK, lw=1.6, zorder=8))
    ax.plot([head_c[0], shoulder[0]], [head_c[1] - 96.0, shoulder[1]],
            color=INK, lw=2.6, solid_capstyle="round", zorder=7)
    for p in (HIP, shoulder, knee, ankle):
        joint(ax, p, INK)
    for p in (elbow, grip):
        joint(ax, p, ACCENT, r=14.0)
    ax.plot([eye[0]], [eye[1]], marker="o", ms=3.0, color=BLUE, zorder=10)
    ax.text(head_c[0] - 118.0, head_c[1], "eye point", ha="right",
            va="center", fontsize=6.4, color=BLUE)
    ax.text(shoulder[0] - 40.0, shoulder[1] + 6.0, "shoulder pivot",
            ha="right", va="bottom", fontsize=6.4, color=SUB)
    ax.text(HIP[0] - 40.0, HIP[1] + 30.0, "H-point\n(seat reference)",
            ha="right", va="bottom", fontsize=6.4, color=SUB,
            linespacing=1.4)

    # controls, coloured by the envelope geometry
    rows = []
    for name, r, th in CONTROLS:
        p = shoulder + r * np.array([np.cos(np.deg2rad(th)),
                                     np.sin(np.deg2rad(th))])
        acc = accommodated(g, cdf, r)
        if r <= r05:
            col, verdict = TEAL, "within 5th pct envelope"
        elif r <= r50:
            col, verdict = AMBER, "beyond 5th pct envelope"
        else:
            col, verdict = RUST, "beyond 50th pct envelope"
        rows.append((name, r, p, acc, col, verdict))
        ax.plot([p[0]], [p[1]], marker="o", ms=7.0, mfc=col, mec="white",
                mew=1.1, zorder=11)
        mark = "+" if col is TEAL else "!"
        ax.text(p[0], p[1] - 2.0, mark, ha="center", va="center",
                fontsize=6.4, color="white", fontweight="bold", zorder=12)
        below = name == "aux breaker panel"
        ax.text(p[0], p[1] + (-36.0 if below else 34.0),
                f"{name}\n{r:.0f} mm, {acc:.0f} % reach", ha="center",
                va="top" if below else "bottom", fontsize=6.2, color=INK,
                linespacing=1.35, zorder=12)

    ax.set_xlim(-430.0, 1130.0)
    ax.set_ylim(-470.0, 1030.0)
    ax.set_xticks(np.arange(-400, 1101, 200))
    ax.set_yticks(np.arange(-400, 1001, 200))
    ax.tick_params(labelsize=6.8)
    ax.set_xlabel("forward of the H-point (mm)", fontsize=8.5)
    ax.set_ylabel("above the H-point (mm)", fontsize=8.5)
    ax.set_title("Seated grip reach, side view: linkage envelopes at three "
                 "body sizes", fontsize=9.0, fontweight="bold", pad=5.0)

    handles = [
        Line2D([], [], color="#134a76", lw=1.3,
               label=f"5th pct female, reach {r05:.0f} mm"),
        Line2D([], [], color="#5f9dc6", lw=1.3,
               label=f"50th pct, reach {r50:.0f} mm"),
        Line2D([], [], color="#9cc3dd", lw=1.3,
               label=f"95th pct male, reach {r95:.0f} mm"),
        Line2D([], [], color="#134a76", lw=0.9, ls=(0, (3.0, 2.2)),
               label=f"inner limit, elbow at {ELBOW_MAX_DEG:.0f} deg "
                     f"({inner_r:.0f} mm)"),
        Line2D([], [], marker="o", ls="none", ms=4.6, mfc=TEAL, mec="white",
               mew=0.8, label="control within 5th pct envelope"),
        Line2D([], [], marker="o", ls="none", ms=4.6, mfc=AMBER, mec="white",
               mew=0.8, label="beyond 5th pct envelope"),
        Line2D([], [], marker="o", ls="none", ms=4.6, mfc=RUST, mec="white",
               mew=0.8, label="beyond 50th pct envelope"),
    ]
    ax.legend(handles=handles, loc="lower left", frameon=False, fontsize=6.5,
              handlelength=1.5, labelspacing=0.30, borderpad=0.15,
              bbox_to_anchor=(-0.006, -0.008))

    # ---- aux (b): reach distributions --------------------------------------
    ax_t.grid(color=GRID, lw=0.5, alpha=0.65, zorder=0)
    ax_t.plot(g, pdf_f * 1000.0, color="#8e6bbf", lw=1.3, zorder=4,
              label=f"women (mean {MU_F:.0f} mm)")
    ax_t.plot(g, pdf_m * 1000.0, color=TEAL, lw=1.3, zorder=4,
              label=f"men (mean {MU_M:.0f} mm)")
    ax_t.plot(g, pdf_p * 1000.0, color=INK, lw=1.6, zorder=5,
              label="pooled 50/50")
    ax_t.fill_between(g, 0.0, pdf_p * 1000.0, facecolor="#eeeeee",
                      edgecolor="none", zorder=1)
    for q, val in ((5, r05), (50, r50), (95, r95)):
        ax_t.axvline(val, color=FAINT, lw=0.9, ls=(0, (3.0, 2.2)), zorder=3)
        ax_t.text(val, 10.6, f"{q}th\n{val:.0f}", ha="center", va="top",
                  fontsize=6.0, color=SUB, linespacing=1.3)
    ax_t.set_xlim(540.0, 960.0)
    ax_t.set_ylim(0.0, 12.0)
    ax_t.set_xticks([600, 700, 800, 900])
    ax_t.set_yticks([0, 4, 8, 12])
    ax_t.tick_params(labelsize=6.6)
    ax_t.set_xlabel("functional grip reach (mm)", fontsize=7.6, labelpad=1.5)
    ax_t.set_ylabel("density (1/m)", fontsize=7.6, labelpad=2.0)
    ax_t.set_title("Percentiles come from the pooled curve", fontsize=8.4,
                   fontweight="bold", pad=4.0)
    ax_t.legend(loc="upper right", frameon=False, fontsize=6.1,
                handlelength=1.3, labelspacing=0.26, borderpad=0.12,
                bbox_to_anchor=(1.012, 1.03))

    # ---- aux (c): accommodation per control --------------------------------
    order = np.argsort([r[3] for r in rows])
    names = [rows[i][0] for i in order]
    accs = np.array([rows[i][3] for i in order])
    cols = [rows[i][4] for i in order]
    ypos = np.arange(len(rows))
    ax_b.grid(axis="x", color=GRID, lw=0.5, alpha=0.65, zorder=0)
    ax_b.barh(ypos, accs, height=0.58, color=cols, edgecolor="white",
              linewidth=0.7, zorder=3)
    ax_b.axvline(95.0, color=ACCENT, lw=1.0, ls=(0, (3.0, 2.2)), zorder=5)
    ax_b.text(94.0, len(rows) - 0.30, "95 % design target", ha="right",
              va="top", fontsize=6.1, color=ACCENT)
    for k in ypos:
        ax_b.text(accs[k] + 1.6, k, f"{accs[k]:.1f} %", ha="left",
                  va="center", fontsize=6.3, color=INK)
    ax_b.set_yticks(ypos)
    ax_b.set_yticklabels(names, fontsize=6.4)
    ax_b.set_ylim(-0.7, len(rows) - 0.30)
    ax_b.set_xlim(0.0, 118.0)
    ax_b.set_xticks([0, 25, 50, 75, 100])
    ax_b.tick_params(axis="x", labelsize=6.6)
    ax_b.set_xlabel("population accommodated (%)", fontsize=7.6, labelpad=1.5)
    ax_b.set_title("Who can reach each control", fontsize=8.4,
                   fontweight="bold", pad=4.0)

    panel_labels_inches(fig, [ax, ax_t, ax_b], dx=-0.62, dy=0.12)
    savefig(fig, "951_hfe_anthropometry_reach.png")


if __name__ == "__main__":
    main()

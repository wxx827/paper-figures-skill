"""Goal, options and primitive actions as nested time bars on one axis.

Three levels of temporal abstraction share a single time axis, so containment
is something the reader can see rather than something the caption claims: the
goal bar spans the episode, seven option calls tile it, and every primitive
action sits inside the option that invoked it.  The alternating pale columns
are the option spans extended through all three levels, which is what makes the
nesting legible at a glance; the accent markers are the points at which an
option's termination condition fired.

Containment is enforced, not hoped for.  Primitive intervals are generated by
subdividing their parent option's interval, and the script asserts that every
child lies inside its parent and every option inside the goal before drawing.
The mean option duration printed in the header is the division of the two
integers printed beside it.

Aspect: a row-count-driven gantt, so DESIGN_SYSTEM section 1.2 exception E5
would apply -- but at fifteen row slots the delivered ratio lands inside the
0.55-0.80 band anyway and the exception is not claimed.

Single-hue blue ladder (BRIEF_WM_BLUE.md section 2); the one warm accent marks
termination triggers only.
"""
import textwrap

import numpy as np
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import FancyBboxPatch, Patch, Rectangle

from pubstyle import set_pub_style, savefig

BLUE = ["#12314f", "#1f4e79", "#2f6fa8", "#4a8cc7", "#7fb0dc", "#b3d0ea",
        "#dce9f5", "#f2f7fb"]
INK = "#22272b"
ACCENT = "#b5544a"
BAND_A = "#dfe7ef"          # luminance 0.90, safely inside the ink count
BAND_B = "#f4f8fb"          # luminance 0.97, safely outside it
HAIR = "#aab7c4"

FW, FH = 10.4, 6.05
GOAL = "assemble tray"

OPTIONS = ["locate.part", "approach", "grasp.part", "transport",
           "place.part", "verify.fit"]
# (option index, start, end) in seconds; the seven calls tile the episode and
# every duration is an exact tenth, so the mean printed in the header closes
CALLS = [(0, 0.0, 5.2), (1, 5.2, 10.4), (2, 10.4, 17.1), (3, 17.1, 24.6),
         (4, 24.6, 30.2), (5, 30.2, 36.0), (3, 36.0, 46.5)]

PRIMS = ["cam.snap", "pose.est", "cart.servo", "joint.servo", "ft.sense",
         "gripper.close", "gripper.open", "wait.settle"]
# which primitives each option expands into, in execution order
EXPAND = {
    0: ["cam.snap", "pose.est", "cam.snap", "pose.est"],
    1: ["cart.servo", "joint.servo", "wait.settle"],
    2: ["cart.servo", "ft.sense", "gripper.close", "wait.settle", "ft.sense"],
    3: ["joint.servo", "cart.servo", "joint.servo", "wait.settle"],
    4: ["cart.servo", "ft.sense", "gripper.open", "wait.settle"],
    5: ["cam.snap", "pose.est", "ft.sense"],
}

INSET, GAP = 0.14, 0.11     # seconds kept clear inside and between siblings
BAR_H = 0.56


def expand_calls():
    """Subdivide each option interval into its primitives; nesting is exact."""
    rng = np.random.default_rng(1617)
    out = []
    for ci, (opt, s, e) in enumerate(CALLS):
        kinds = EXPAND[opt]
        n = len(kinds)
        usable = (e - s) - 2 * INSET - (n - 1) * GAP
        w = rng.uniform(0.72, 1.30, n)
        w = w / w.sum() * usable
        t = s + INSET
        for k, kind in enumerate(kinds):
            out.append((PRIMS.index(kind), float(t), float(t + w[k]), ci))
            t += w[k] + GAP
    return out


def main():
    set_pub_style(base_font=8)
    prims = expand_calls()
    t_end = CALLS[-1][2]

    for opt, s, e in CALLS:
        assert 0.0 <= s < e <= t_end, "option escapes the goal interval"
    for _, ps, pe, ci in prims:
        _, s, e = CALLS[ci]
        assert s <= ps < pe <= e, "primitive escapes its parent option"
    for a, b in zip(CALLS, CALLS[1:]):
        assert abs(a[2] - b[1]) < 1e-9, "option calls must tile the episode"

    dur = [e - s for _, s, e in CALLS]
    tot_s, n_call = "%.1f" % sum(dur), len(CALLS)
    mean_s = "%.2f" % (float(tot_s) / n_call)
    assert abs(float(tot_s) / n_call - float(mean_s)) < 5e-3, "mean not closed"
    p_time = sum(pe - ps for _, ps, pe, _ in prims)
    duty = "%.1f" % (100.0 * p_time / t_end)

    # ---- row geometry: goal, a gap, six option rows, a gap, eight prim rows
    y_goal = 0.0
    y_opt = {k: 1.55 + k for k in range(len(OPTIONS))}
    y_pr = {k: 8.15 + k for k in range(len(PRIMS))}
    y_lo, y_hi = -0.85, max(y_pr.values()) + 0.85

    fig = plt.figure(figsize=(FW, FH))
    ax = fig.add_axes([1.80 / FW, 0.86 / FH, 8.27 / FW, 4.30 / FH])
    ax.set_xlim(0.0, t_end * 1.012)
    ax.set_ylim(y_hi, y_lo)                       # top-down
    ax.set_yticks([])
    ax.set_xlabel("episode time (s)", fontsize=8.0, labelpad=2.2)
    ax.tick_params(labelsize=7.2, length=2.6, pad=1.8)
    for side in ("left", "bottom"):
        ax.spines[side].set_linewidth(0.8)
        ax.spines[side].set_color("#7f8c99")

    # alternating option columns, carried through all three levels
    for ci, (_, s, e) in enumerate(CALLS):
        ax.add_patch(Rectangle((s, y_lo), e - s, y_hi - y_lo,
                               facecolor=BAND_A if ci % 2 == 0 else BAND_B,
                               edgecolor="none", zorder=1))
        ax.plot([s, s], [y_lo, y_hi], color="#b4c2cf", lw=0.7,
                ls=(0, (2.4, 2.0)), zorder=2)
    ax.plot([t_end, t_end], [y_lo, y_hi], color="#b4c2cf", lw=0.7,
            ls=(0, (2.4, 2.0)), zorder=2)

    def bar(y, s, e, fc, ec, h=BAR_H, z=5, lw=0.8):
        ax.add_patch(FancyBboxPatch(
            (s, y - h / 2.0), e - s, h,
            boxstyle="round,pad=0,rounding_size=0.16", facecolor=fc,
            edgecolor=ec, linewidth=lw, mutation_aspect=0.030, zorder=z))

    # level 1
    bar(y_goal, 0.0, t_end, BLUE[0], "white", h=0.66, z=5, lw=1.0)
    ax.text(t_end / 2.0, y_goal, GOAL, ha="center", va="center", fontsize=7.6,
            color="white", fontweight="bold", zorder=7)

    # level 2 plus the termination trigger at the close of every call
    for ci, (opt, s, e) in enumerate(CALLS):
        bar(y_opt[opt], s, e, BLUE[2], "white", z=5)
        ax.text((s + e) / 2.0, y_opt[opt], "%.1f s" % (e - s), ha="center",
                va="center", fontsize=6.6, color="white", zorder=7)
        ax.plot([e], [y_opt[opt]], marker="v", ms=5.0, mfc=ACCENT,
                mec="white", mew=0.7, ls="none", zorder=8)
        ax.plot([e, e], [y_opt[opt] - 0.30, y_opt[opt] + 0.30], color=ACCENT,
                lw=1.2, zorder=8)

    # level 3
    for pi, ps, pe, ci in prims:
        bar(y_pr[pi], ps, pe, BLUE[4], BLUE[1], h=0.46, z=5, lw=0.6)

    # ---- row labels and level brackets ------------------------------------
    ax.text(-0.9, y_goal, GOAL, ha="right", va="center", fontsize=7.4,
            color=INK, fontweight="bold", clip_on=False)
    for k, nm in enumerate(OPTIONS):
        ax.text(-0.9, y_opt[k], nm, ha="right", va="center", fontsize=7.2,
                color=INK, clip_on=False)
    for k, nm in enumerate(PRIMS):
        ax.text(-0.9, y_pr[k], nm, ha="right", va="center", fontsize=7.0,
                color="#3f4b57", clip_on=False)

    levels = [("level 1  goal", y_goal - 0.42, y_goal + 0.42),
              ("level 2  options", y_opt[0] - 0.52,
               y_opt[len(OPTIONS) - 1] + 0.52),
              ("level 3  primitive actions", y_pr[0] - 0.52,
               y_pr[len(PRIMS) - 1] + 0.52)]
    for nm, ya, yb in levels:
        ax.plot([-8.9, -8.4, -8.4, -8.9], [ya, ya, yb, yb], color=BLUE[1],
                lw=1.0, clip_on=False, zorder=6)
        ax.text(-9.35, (ya + yb) / 2.0, nm, ha="center", va="center",
                rotation=90, fontsize=7.4, color=BLUE[1], fontweight="bold",
                clip_on=False)

    # one worked call-out on a single trigger
    ci = 2
    _, _, e2 = CALLS[ci]
    ax.annotate("termination condition $\\beta(s)=1$:\nthe option returns "
                "control here", xy=(e2, y_opt[CALLS[ci][0]] + 0.34),
                xytext=(9.6, 6.15), fontsize=7.0,
                color=ACCENT, fontweight="bold", ha="center", va="center",
                zorder=10, linespacing=1.4,
                bbox=dict(boxstyle="round,pad=0.28", fc="white",
                          ec="#d9c4c1", lw=0.7, alpha=0.96),
                arrowprops=dict(arrowstyle="-", color=ACCENT, lw=0.9,
                                shrinkA=3.0, shrinkB=3.0))
    ax.text(t_end, 7.35, "%d option calls over %d distinct options  ·  "
            "%d primitive actions  ·  primitives occupy %s %% of the episode"
            % (n_call, len(OPTIONS), len(prims), duty),
            ha="right", va="center", fontsize=6.9, color=INK, zorder=10,
            bbox=dict(boxstyle="round,pad=0.28", fc="white", ec="#c3ccd4",
                      lw=0.6, alpha=0.96))

    handles = [
        Patch(facecolor=BLUE[0], edgecolor="white", label="goal"),
        Patch(facecolor=BLUE[2], edgecolor="white", label="option call"),
        Patch(facecolor=BLUE[4], edgecolor=BLUE[1], label="primitive action"),
        Line2D([], [], color=ACCENT, lw=1.2, marker="v", ms=4.6, mfc=ACCENT,
               mec="white", label="termination trigger"),
        Line2D([], [], color="#b4c2cf", lw=0.9, ls=(0, (2.4, 2.0)),
               label="option boundary"),
    ]

    savefig(fig, "1212_wm_plan_option_hierarchy.png")


if __name__ == "__main__":
    main()
